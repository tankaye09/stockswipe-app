const today = new Date();
const isoDaysFromNow = (d: number) => {
  const t = new Date(today);
  t.setDate(t.getDate() + d);
  return t.toISOString().slice(0, 10);
};

const capBucket = (capB: number, currency: Currency): CapBucket => {
  const usd = currency === 'SGD' ? capB * 0.77 : capB;
  if (usd >= 200) return 'mega';
  if (usd >= 10) return 'large';
  if (usd >= 2) return 'mid';
  return 'small';
};

const build = (market: Market, currency: Currency, seeds: Seed[]): StockSummary[] =>
  seeds.map((s) => ({
    symbol: s.symbol,
    market,
    currency,
    name: s.name,
    sector: s.sector,
    themes: s.themes,
    capBucket: capBucket(s.capB, currency),
    price: s.price,
    changePct: s.changePct,
    stats: {
      marketCap: s.capB * 1e9,
      peRatio: s.pe,
      dividendYield: s.div,
      week52High: +(s.price * 1.18).toFixed(2),
      week52Low: +(s.price * 0.71).toFixed(2),
      nextEarnings: s.earningsInDays == null ? null : isoDaysFromNow(s.earningsInDays),
    },
    breakdown: {
      oneLiner: s.oneLiner,
      whatTheyDo: s.what,
      howTheyMakeMoney: s.money,
      whyPeopleWatch: s.watch,
      risksToKnow: s.risks,
    },
    news: s.news ? [{ headline: s.news, source: 'Sample Wire', date: isoDaysFromNow(-1) }] : [],
  }));

